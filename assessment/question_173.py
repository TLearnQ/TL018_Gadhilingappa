# cpu,users

        
def machine(cpu, users):
    if cpu < 20 and users == 0:
        return "Idle"
    elif cpu < 50:
        return "Normal"
    elif cpu < 80:
        return "Busy"
    else:
        return "Overloaded"

machines = [
    {"cpu": 45, "users": 2},
    {"cpu": 89, "users": 4},
]

for m in machines:
    print(machine(m["cpu"], m["users"]))
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
  